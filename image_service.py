"""
Vaelkry Dev Labs - Multi-Agent Enterprise Discord System
Pollinations AI Direct Visual Generator
Generates UI mockups, tech assets, and autonomous squad graphics without API key restrictions.
"""

import urllib.parse
import discord
from typing import Optional

class ImageService:
    BASE_URL = "https://image.pollinations.ai/prompt/"

    @classmethod
    def generate_image_url(
        cls,
        prompt: str,
        width: int = 1024,
        height: int = 1024,
        model: str = "flux",
        seed: Optional[int] = None,
        nologo: bool = True,
    ) -> str:
        """
        Builds a direct streaming Pollinations image URL.
        """
        encoded_prompt = urllib.parse.quote(prompt.strip())
        params = [f"width={width}", f"height={height}", f"model={model}"]
        if nologo:
            params.append("nologo=true")
        if seed is not None:
            params.append(f"seed={seed}")

        query_string = "&".join(params)
        return f"{cls.BASE_URL}{encoded_prompt}?{query_string}"

    @classmethod
    def create_image_embed(
        cls,
        prompt: str,
        author_name: str,
        squad_name: str = "Vaelkry Design Squad",
        model: str = "flux",
    ) -> discord.Embed:
        """
        Constructs a branded Discord embed wrapping the generated visual asset.
        """
        image_url = cls.generate_image_url(prompt, model=model)

        embed = discord.Embed(
            title="🎨 Vaelkry Dev Labs | Autonomous Asset Render",
            description=f"**Prompt:** {prompt}\n**Generated By:** `{author_name}` ({squad_name})",
            color=0x5865F2,
        )
        embed.set_image(url=image_url)
        embed.set_footer(text=f"Engine: Pollinations ({model.upper()}) | Zero-Latency Pipeline")
        return embed